-- One pending submission per contributor per task.
--
-- A contributor can submit, be sent back for revisions and submit again, but they cannot
-- have two submissions awaiting review at the same time. That state is meaningless for the
-- owner (which one are they reviewing?) and is the usual symptom of a double-clicked or
-- retried form post.
--
-- Enforced as a partial unique index so the rule holds even if two requests race past the
-- service-layer check in src/services/tasks.ts. Reviewed submissions are unaffected: once a
-- row leaves the `submitted` status it drops out of the index.
--
-- Hand-written rather than generated by drizzle-kit: Drizzle's SQLite index builder cannot
-- express partial indexes, so this constraint lives only in the migration history.

CREATE UNIQUE INDEX IF NOT EXISTS submissions_one_pending_per_contributor_idx
ON task_submissions (task_id, user_id)
WHERE status = 'submitted';
